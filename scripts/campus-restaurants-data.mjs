export function imageForItem(item) {
  const value = (item.category + " " + item.name).toLowerCase();

  if (/(coffee|latte|cappuccino|matcha|hot chocolate)/.test(value)) return FOOD_IMAGES.coffee;
  if (/(milkshake|smoothie|parfait|ice cream|yoghurt|yogurt|boba|chocolate milk|nutri milk|nutri choco|peak milk)/.test(value)) return FOOD_IMAGES.milkshake;
  if (/(shawarma|wrap|fajita)/.test(value)) return FOOD_IMAGES.shawarma;
  if (/burger/.test(value)) return FOOD_IMAGES.burger;
  if (/(wing|fried chicken|peppered chicken|chicken strip|chicken part|chicken thigh|chicken breast|chicken leg)/.test(value)) return FOOD_IMAGES.wings;
  if (/(fries|chips|yamarita|fried yam|plantain fries|loaded plantain|potato wedge)/.test(value)) return FOOD_IMAGES.fries;
  if (/(noodle|indomie)/.test(value)) return FOOD_IMAGES.noodles;
  if (/(pasta|spaghetti|macaroni|rigatoni|linguine|bolognese)/.test(value)) return FOOD_IMAGES.pasta;
  if (/(sandwich|sub|philly|tuna melt)/.test(value)) return FOOD_IMAGES.sandwich;
  if (/(rice|rice & beans|porridge beans|beans)/.test(value)) return FOOD_IMAGES.rice;
  if (/(soup|egusi|okro|ogbono|miyan|stew|tuwon|semo|semovita|eba|fufu|poundo|garri|moi moi|moin moin)/.test(value)) return FOOD_IMAGES.soup;
  if (/(cake|cupcake|muffin|doughnut|donut|cinnamon roll|meat pie|chicken pie|fish roll|sausage roll|season roll|cookie|puff puff|buns|popcorn)/.test(value)) return FOOD_IMAGES.dessert;
  if (/(drink|water|coke|fanta|sprite|malt|chapman|mojito|lemonade|lemonde|zobo|ginger|sosa|ribena|peach|mirinda|chivita|la casera|predator|fearless|lucozade|power horse|monster|schweppes)/.test(value)) return FOOD_IMAGES.drinks;
  return FOOD_IMAGES.general;
}

